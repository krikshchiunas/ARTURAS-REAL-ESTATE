/**
 * Нужно ли предзагружать маршрут по ссылке.
 *
 * Карта — единственная тяжёлая страница проекта: three.js + R3F дают 413 кБ
 * First Load против 112 кБ у всех остальных. Ссылка на неё («Projects») стоит
 * в шапке, в футере и в мобильном меню, то есть присутствует на каждой
 * странице сайта. Next в проде предзагружает <Link>, попавшие в кадр, — и
 * бандл карты уезжал к посетителю всегда, даже если карту он не откроет.
 * Замер: 424 кБ JS на главной против 113 кБ, которые показывает сборка.
 *
 * `prefetch={false}` отключает только предзагрузку «по видимости». На
 * hover и touchstart Next всё равно подтянет маршрут заранее, поэтому по
 * ощущениям переход на карту остаётся мгновенным — платит за него лишь тот,
 * кто к ссылке потянулся.
 */
export function linkPrefetch(href: string): false | undefined {
  return /\/map(\/|$)/.test(href) ? false : undefined;
}
